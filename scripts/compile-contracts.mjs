import fs from "node:fs";
import path from "node:path";
import solc from "solc";
const sources = {};
for (const folder of ["contracts/src", "contracts/script"]) {
    if (!fs.existsSync(folder)) continue;
    for (const name of fs.readdirSync(folder))
        if (name.endsWith(".sol"))
            sources[`${folder}/${name}`] = {
                content: fs.readFileSync(`${folder}/${name}`, "utf8"),
            };
}
const input = {
    language: "Solidity",
    sources,
    settings: {
        optimizer: { enabled: true, runs: 200 },
        viaIR: true,
        evmVersion: "cancun",
        outputSelection: {
            "*": {
                "*": [
                    "abi",
                    "storageLayout",
                    "evm.bytecode.object",
                    "evm.deployedBytecode.object",
                ],
            },
        },
    },
};
const output = JSON.parse(
    solc.compile(JSON.stringify(input), {
        import: (name) => {
            for (const candidate of [name, path.join("node_modules", name)])
                if (fs.existsSync(candidate))
                    return { contents: fs.readFileSync(candidate, "utf8") };
            return { error: `Missing import: ${name}` };
        },
    }),
);
for (const error of output.errors ?? []) console.error(error.formattedMessage);
if ((output.errors ?? []).some((error) => error.severity === "error"))
    process.exit(1);
fs.mkdirSync("build/contracts", { recursive: true });
for (const [source, contracts] of Object.entries(output.contracts))
    for (const [name, artifact] of Object.entries(contracts))
        if (source.startsWith("contracts/")) {
            fs.writeFileSync(
                `build/contracts/${name}.json`,
                JSON.stringify(
                    {
                        contractName: name,
                        sourceName: source,
                        abi: artifact.abi,
                        storageLayout: artifact.storageLayout,
                        bytecode: `0x${artifact.evm.bytecode.object}`,
                        deployedBytecode: `0x${artifact.evm.deployedBytecode.object}`,
                    },
                    null,
                    2,
                ),
            );
            if (
                source.startsWith("contracts/src/") &&
                artifact.evm.deployedBytecode.object.length / 2 > 24576
            )
                throw new Error(`${name} exceeds the EVM contract-size limit`);
        }
console.log(
    `Compiled ${Object.keys(sources).length} protocol source files with Solidity ${solc.version()}`,
);

const names = [
    "StellariumBalanceVault",
    "ResourceRegistry",
    "Settlement",
    "FeeOracle",
    "RelayRegistry",
    "ReputationRegistry",
    "ArbitrationCourt",
    "ProtocolTreasury",
    "RandomnessAdapter",
    "Governor",
    "TimelockController",
    "StewardMultisig",
];
fs.writeFileSync(
    "src/payment/abis.ts",
    "// Generated by scripts/compile-contracts.mjs; do not edit.\nimport type { Abi } from 'viem';\nexport const abis: Record<string,Abi> = " +
        JSON.stringify(
            Object.fromEntries(
                names.map((name) => [
                    name,
                    JSON.parse(fs.readFileSync(`build/contracts/${name}.json`))
                        .abi,
                ]),
            ),
        ) +
        ";\n",
);
